import Cocoa
import SwiftUI

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var text: String
    var date: Date
}

/// Records copied text. Items marked as concealed/transient by password managers are never stored.
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    @Published private(set) var items: [ClipItem] = []
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var ignoreCount = -1

    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword")]

    private var fileURL: URL? {
        guard let base = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first else { return nil }
        return base.appendingPathComponent("WindowPac/clipboard.json")
    }

    /// Start or stop recording according to the settings.
    func apply() {
        timer?.invalidate(); timer = nil
        if Settings.clipboardPersist { if items.isEmpty { load() } } else { deleteFile() }
        guard Settings.clipboardEnabled else { return }
        lastCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer!, forMode: .common)
        trim()
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        if lastCount == ignoreCount { return }
        let types = pb.types ?? []
        if types.contains(where: { Self.skipTypes.contains($0) }) { return }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= 50_000 else { return }
        items.removeAll { $0.text == text }
        items.insert(ClipItem(text: text, date: Date()), at: 0)
        trim()
        save()
    }

    private func trim() {
        if items.count > Settings.clipboardMax { items = Array(items.prefix(Settings.clipboardMax)) }
    }

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id }; save() }
    func clear() { items = []; save() }

    /// Puts the item on the pasteboard without recording it as a new copy.
    func setPasteboard(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        ignoreCount = pb.changeCount
        lastCount = pb.changeCount
        if let i = items.firstIndex(of: item) { items.insert(items.remove(at: i), at: 0); save() }
    }

    // MARK: Persistence (owner-only file)

    private func save() {
        guard Settings.clipboardPersist, let url = fileURL else { return }
        do {
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try JSONEncoder().encode(items).write(to: url, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        } catch { NSLog("WindowPac: could not save clipboard history: \(error)") }
    }

    private func load() {
        guard let url = fileURL, let data = try? Data(contentsOf: url),
              let list = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = list
    }

    private func deleteFile() { if let url = fileURL { try? FileManager.default.removeItem(at: url) } }
}

private final class KeyPanel: NSPanel {
    override var canBecomeKey: Bool { true }
}

/// Spotlight-like popup listing the history; Return / click pastes into the app you were in.
final class ClipboardPanel {
    private var panel: KeyPanel?
    private var resignObserver: NSObjectProtocol?

    func toggle() { panel?.isVisible == true ? hide() : show() }

    private func show() {
        guard Settings.clipboardEnabled else { return }
        let view = ClipboardView(store: .shared, onPick: { [weak self] in self?.pick($0) }, onClose: { [weak self] in self?.hide() })
        let host = NSHostingView(rootView: view)
        let p = panel ?? KeyPanel(contentRect: CGRect(x: 0, y: 0, width: 460, height: 420),
                                  styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
        p.level = .floating
        p.isOpaque = false
        p.backgroundColor = .clear
        p.hasShadow = true
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        p.contentView = host
        let screen = NSScreen.screens.first { NSMouseInRect(NSEvent.mouseLocation, $0.frame, false) } ?? NSScreen.main
        if let f = screen?.visibleFrame {
            p.setFrameOrigin(CGPoint(x: f.midX - 230, y: f.midY - 150))
        }
        panel = p
        p.makeKeyAndOrderFront(nil)
        if resignObserver == nil {
            resignObserver = NotificationCenter.default.addObserver(
                forName: NSWindow.didResignKeyNotification, object: p, queue: .main) { [weak self] _ in self?.hide() }
        }
    }

    private func hide() { panel?.orderOut(nil) }

    private func pick(_ item: ClipItem) {
        ClipboardStore.shared.setPasteboard(item)
        hide()
        // The panel never activated WindowPac, so the previous app is still frontmost: send ⌘V to it.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }
}

private struct ClipboardView: View {
    @ObservedObject var store: ClipboardStore
    var onPick: (ClipItem) -> Void
    var onClose: () -> Void
    @State private var query = ""
    @State private var selection = 0
    @FocusState private var focused: Bool

    private static let rel: RelativeDateTimeFormatter = {
        let f = RelativeDateTimeFormatter(); f.unitsStyle = .short; return f
    }()

    private var filtered: [ClipItem] {
        query.isEmpty ? store.items : store.items.filter { $0.text.localizedCaseInsensitiveContains(query) }
    }

    private func move(_ d: Int) {
        guard !filtered.isEmpty else { return }
        selection = min(max(selection + d, 0), filtered.count - 1)
    }

    private func pickSelected() {
        if filtered.indices.contains(selection) { onPick(filtered[selection]) }
    }

    var body: some View {
        VStack(spacing: 0) {
            TextField("Search clipboard history…", text: $query)
                .textFieldStyle(.plain)
                .font(.system(size: 15))
                .padding(12)
                .focused($focused)
                .onKeyPress(.downArrow) { move(1); return .handled }
                .onKeyPress(.upArrow) { move(-1); return .handled }
                .onKeyPress(.escape) { onClose(); return .handled }
                .onSubmit { pickSelected() }
                .onChange(of: query) { _, _ in selection = 0 }
            Divider()
            if filtered.isEmpty {
                Spacer()
                Text(store.items.isEmpty ? "Nothing copied yet" : "No matches")
                    .foregroundStyle(.secondary)
                Spacer()
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 0) {
                            ForEach(Array(filtered.enumerated()), id: \.element.id) { i, item in
                                row(item, selected: i == selection).id(item.id)
                                    .contentShape(Rectangle())
                                    .onTapGesture { onPick(item) }
                            }
                        }
                    }
                    .onChange(of: selection) { _, new in
                        if filtered.indices.contains(new) { proxy.scrollTo(filtered[new].id) }
                    }
                }
            }
            Divider()
            HStack {
                Text("↩ paste   ↑↓ select   ⎋ close").font(.system(size: 11)).foregroundStyle(.secondary)
                Spacer()
                Button("Clear all") { store.clear() }.buttonStyle(.plain).font(.system(size: 11)).foregroundStyle(.secondary)
            }
            .padding(.horizontal, 12).padding(.vertical, 8)
        }
        .frame(width: 460, height: 420)
        .background(.regularMaterial, in: RoundedRectangle(cornerRadius: 14))
        .onAppear { focused = true }
    }

    private func row(_ item: ClipItem, selected: Bool) -> some View {
        HStack(alignment: .top, spacing: 8) {
            VStack(alignment: .leading, spacing: 2) {
                Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                    .font(.system(size: 12)).lineLimit(2).truncationMode(.tail)
                Text(Self.rel.localizedString(for: item.date, relativeTo: Date()))
                    .font(.system(size: 10)).foregroundStyle(.secondary)
            }
            Spacer(minLength: 0)
            Button { store.remove(item) } label: { Image(systemName: "xmark.circle.fill") }
                .buttonStyle(.plain).foregroundStyle(.tertiary)
        }
        .padding(.horizontal, 12).padding(.vertical, 6)
        .background(selected ? Color.accentColor.opacity(0.25) : Color.clear)
    }
}
