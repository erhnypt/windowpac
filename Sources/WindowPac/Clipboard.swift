import Cocoa
import SwiftUI
import CryptoKit

enum ClipKind: String, Codable { case text, image, files }

struct ClipItem: Identifiable, Codable, Equatable {
    var id = UUID()
    var kind: ClipKind = .text
    /// text: the copied text · image: SHA-256 of the PNG (identity) · files: the paths, one per line.
    var text: String
    var date: Date
    /// Pinned items are never trimmed, cleared or deleted (only unpinning makes them removable).
    var pinned = false
    /// Set for snippets: named notes created in Settings. Always pinned, only removable from Settings.
    var title: String?
    var imageFile: String?
    var imageSize: String?

    var isSnippet: Bool { title != nil }
    var paths: [String] { kind == .files ? text.split(separator: "\n").map(String.init) : [] }

    init(text: String, date: Date) { self.text = text; self.date = date }

    init(from decoder: Decoder) throws {
        let c = try decoder.container(keyedBy: CodingKeys.self)
        id = try c.decode(UUID.self, forKey: .id)
        text = try c.decode(String.self, forKey: .text)
        date = try c.decode(Date.self, forKey: .date)
        // Fields added later: history saved by older versions simply lacks them.
        pinned = try c.decodeIfPresent(Bool.self, forKey: .pinned) ?? false
        kind = try c.decodeIfPresent(ClipKind.self, forKey: .kind) ?? .text
        title = try c.decodeIfPresent(String.self, forKey: .title)
        imageFile = try c.decodeIfPresent(String.self, forKey: .imageFile)
        imageSize = try c.decodeIfPresent(String.self, forKey: .imageSize)
    }
}

/// Records copied text, images and files. Items marked concealed/transient by password managers, and anything
/// copied while an ignored app is frontmost, are never stored.
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    @Published private(set) var items: [ClipItem] = []
    private var timer: Timer?
    private var lastCount = NSPasteboard.general.changeCount
    private var ignoreCount = -1
    private var imageData: [UUID: Data] = [:]
    private var thumbCache: [UUID: NSImage] = [:]

    private static let maxImages = 15
    private static let maxImageBytes = 8_000_000

    private static let skipTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), .init("com.agilebits.onepassword")]

    private var supportDir: URL? {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first?
            .appendingPathComponent("WindowPac")
    }
    private var fileURL: URL? { supportDir?.appendingPathComponent("clipboard.json") }
    private var imagesDir: URL? { supportDir?.appendingPathComponent("images") }

    var snippets: [ClipItem] { items.filter(\.isSnippet) }

    /// Start or stop recording according to the settings.
    func apply() {
        timer?.invalidate(); timer = nil
        if items.isEmpty { load() }
        save()   // also drops unpinned items from disk when "keep after restart" was turned off
        guard Settings.clipboardEnabled else { return }
        lastCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        RunLoop.main.add(timer!, forMode: .common)
        trim()
    }

    // MARK: Recording

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastCount else { return }
        lastCount = pb.changeCount
        if lastCount == ignoreCount { return }
        if (pb.types ?? []).contains(where: { Self.skipTypes.contains($0) }) { return }
        if let bid = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           Settings.clipboardIgnoredApps.contains(bid) { return }

        // Files first (Finder also puts names / an icon on the pasteboard), then text, then a bare image.
        if Settings.clipboardFiles,
           let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL],
           !urls.isEmpty {
            record(kind: .files, text: urls.map(\.path).joined(separator: "\n"), image: nil)
            return
        }
        if let text = pb.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty, text.count <= 50_000 {
            record(kind: .text, text: text, image: nil)
            return
        }
        if Settings.clipboardImages, let png = pngData(from: pb), png.count <= Self.maxImageBytes {
            let hash = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
            record(kind: .image, text: hash, image: png)
        }
    }

    private func pngData(from pb: NSPasteboard) -> Data? {
        if let d = pb.data(forType: .png) { return d }
        if let tiff = pb.data(forType: .tiff), let rep = NSBitmapImageRep(data: tiff) {
            return rep.representation(using: .png, properties: [:])
        }
        return nil
    }

    private func record(kind: ClipKind, text: String, image: Data?) {
        if let i = items.firstIndex(where: { $0.kind == kind && $0.text == text && !$0.isSnippet }) {
            if items[i].pinned { return }   // already pinned: leave it where it is
            var it = items.remove(at: i)
            it.date = Date()
            items.insert(it, at: 0)
            save()
            return
        }
        var item = ClipItem(text: text, date: Date())
        item.kind = kind
        if let image {
            item.imageFile = "\(item.id.uuidString).png"
            if let rep = NSBitmapImageRep(data: image) { item.imageSize = "\(rep.pixelsWide)×\(rep.pixelsHigh)" }
            imageData[item.id] = image
        }
        items.insert(item, at: 0)
        trim()
        save()
    }

    private func trim() {
        // The limit only counts unpinned items (snippets are pinned); at most `maxImages` images are kept.
        let removable = items.filter { !$0.pinned }
        var keep = Set(removable.prefix(Settings.clipboardMax).map(\.id))
        var images = 0
        for it in removable where keep.contains(it.id) && it.kind == .image {
            images += 1
            if images > Self.maxImages { keep.remove(it.id) }
        }
        items.removeAll { !$0.pinned && !keep.contains($0.id) }
        let ids = Set(items.map(\.id))
        imageData = imageData.filter { ids.contains($0.key) }
        thumbCache = thumbCache.filter { ids.contains($0.key) }
    }

    // MARK: Editing

    func remove(_ item: ClipItem) { items.removeAll { $0.id == item.id && !$0.pinned }; trim(); save() }
    /// Removes everything except pinned items (and therefore snippets).
    func clear() { items.removeAll { !$0.pinned }; trim(); save() }
    func togglePin(_ item: ClipItem) {
        guard let i = items.firstIndex(where: { $0.id == item.id }), !items[i].isSnippet else { return }
        items[i].pinned.toggle()
        save()
    }

    func addSnippet(title: String, text: String) {
        var it = ClipItem(text: text, date: Date())
        it.title = title
        it.pinned = true
        items.insert(it, at: 0)
        save()
    }

    func updateSnippet(id: UUID, title: String, text: String) {
        guard let i = items.firstIndex(where: { $0.id == id && $0.isSnippet }) else { return }
        items[i].title = title
        items[i].text = text
        save()
    }

    func deleteSnippet(_ id: UUID) { items.removeAll { $0.id == id && $0.isSnippet }; save() }

    // MARK: Images

    func data(for item: ClipItem) -> Data? {
        if let d = imageData[item.id] { return d }
        guard let name = item.imageFile, let url = imagesDir?.appendingPathComponent(name),
              let d = try? Data(contentsOf: url) else { return nil }
        imageData[item.id] = d
        return d
    }

    func thumbnail(for item: ClipItem) -> NSImage? {
        if let t = thumbCache[item.id] { return t }
        guard let d = data(for: item), let img = NSImage(data: d) else { return nil }
        thumbCache[item.id] = img
        return img
    }

    // MARK: Pasting

    /// Puts the item on the pasteboard without recording it as a new copy.
    func setPasteboard(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text, forType: .string)
        case .files:
            let urls: [NSPasteboardWriting] = item.paths.map { NSURL(fileURLWithPath: $0) }
            pb.writeObjects(urls)
        case .image: if let d = data(for: item) { pb.setData(d, forType: .png) }
        }
        ignoreCount = pb.changeCount
        lastCount = pb.changeCount
        if let i = items.firstIndex(where: { $0.id == item.id }), !items[i].pinned {
            items.insert(items.remove(at: i), at: 0); save()
        }
    }

    // MARK: Persistence (owner-only files)

    private func save() {
        guard let url = fileURL else { return }
        // Pinned items (and snippets) are always kept on disk; the rest only when "keep after restart" is on.
        let toSave = Settings.clipboardPersist ? items : items.filter { $0.pinned }
        if toSave.isEmpty { deleteFile(); pruneImages(keeping: []); return }
        do {
            try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
            try JSONEncoder().encode(toSave).write(to: url, options: .atomic)
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            writeImages(for: toSave)
            pruneImages(keeping: Set(toSave.compactMap(\.imageFile)))
        } catch { NSLog("WindowPac: could not save clipboard history: \(error)") }
    }

    private func writeImages(for list: [ClipItem]) {
        guard let dir = imagesDir else { return }
        for it in list {
            guard let name = it.imageFile, let d = imageData[it.id] else { continue }
            let url = dir.appendingPathComponent(name)
            if FileManager.default.fileExists(atPath: url.path) { continue }
            try? FileManager.default.createDirectory(at: dir, withIntermediateDirectories: true)
            try? d.write(to: url, options: .atomic)
            try? FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        }
    }

    private func pruneImages(keeping: Set<String>) {
        guard let dir = imagesDir, let names = try? FileManager.default.contentsOfDirectory(atPath: dir.path) else { return }
        for n in names where !keeping.contains(n) { try? FileManager.default.removeItem(at: dir.appendingPathComponent(n)) }
    }

    private func load() {
        guard let url = fileURL, let data = try? Data(contentsOf: url),
              let list = try? JSONDecoder().decode([ClipItem].self, from: data) else { return }
        items = Settings.clipboardPersist ? list : list.filter { $0.pinned }
    }

    private func deleteFile() { if let url = fileURL { try? FileManager.default.removeItem(at: url) } }
}

private final class KeyPanel: NSPanel {
    override var canBecomeKey: Bool { true }
}

/// Spotlight-like popup listing the history; Return / click pastes into the app you were in.
final class ClipboardPanel {
    private var panel: KeyPanel?
    private var resignObserver: NSObjectProtocol?

    func toggle() { panel?.isVisible == true ? hide() : show() }

    private func show() {
        guard Settings.clipboardEnabled else { return }
        let view = ClipboardView(store: .shared, onPick: { [weak self] in self?.pick($0) }, onClose: { [weak self] in self?.hide() })
        let host = NSHostingView(rootView: view)
        let p = panel ?? KeyPanel(contentRect: CGRect(x: 0, y: 0, width: 460, height: 440),
                                  styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
        p.level = .floating
        p.isOpaque = false
        p.backgroundColor = .clear
        p.hasShadow = true
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        p.contentView = host
        let screen = NSScreen.screens.first { NSMouseInRect(NSEvent.mouseLocation, $0.frame, false) } ?? NSScreen.main
        if let f = screen?.visibleFrame {
            p.setFrameOrigin(CGPoint(x: f.midX - 230, y: f.midY - 160))
        }
        panel = p
        p.makeKeyAndOrderFront(nil)
        if resignObserver == nil {
            resignObserver = NotificationCenter.default.addObserver(
                forName: NSWindow.didResignKeyNotification, object: p, queue: .main) { [weak self] _ in self?.hide() }
        }
    }

    private func hide() { panel?.orderOut(nil) }

    private func pick(_ item: ClipItem) {
        ClipboardStore.shared.setPasteboard(item)
        hide()
        // The panel never activated WindowPac, so the previous app is still frontmost: send ⌘V to it.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            let src = CGEventSource(stateID: .combinedSessionState)
            for down in [true, false] {
                let e = CGEvent(keyboardEventSource: src, virtualKey: 9, keyDown: down)
                e?.flags = .maskCommand
                e?.post(tap: .cghidEventTap)
            }
        }
    }
}

private struct ClipboardView: View {
    @ObservedObject var store: ClipboardStore
    var onPick: (ClipItem) -> Void
    var onClose: () -> Void
    @State private var query = ""
    @State private var selection = 0
    @FocusState private var focused: Bool

    private static let rel: RelativeDateTimeFormatter = {
        let f = RelativeDateTimeFormatter(); f.unitsStyle = .short; return f
    }()

    private func matches(_ it: ClipItem, _ q: String) -> Bool {
        switch it.kind {
        case .image: return "image".contains(q.lowercased()) || (it.imageSize ?? "").contains(q)
        case .files: return it.text.localizedCaseInsensitiveContains(q)
        case .text: return it.text.localizedCaseInsensitiveContains(q) || (it.title ?? "").localizedCaseInsensitiveContains(q)
        }
    }

    /// Snippets first, then pinned entries, then the rest (newest first).
    private var filtered: [ClipItem] {
        let base = query.isEmpty ? store.items : store.items.filter { matches($0, query) }
        return base.filter(\.isSnippet) + base.filter { $0.pinned && !$0.isSnippet } + base.filter { !$0.pinned }
    }

    private func togglePin(_ item: ClipItem) {
        store.togglePin(item)
        // Keep the selection on the same entry after it moved.
        DispatchQueue.main.async { if let i = filtered.firstIndex(where: { $0.id == item.id }) { selection = i } }
    }

    private func move(_ d: Int) {
        guard !filtered.isEmpty else { return }
        selection = min(max(selection + d, 0), filtered.count - 1)
    }

    private func pickSelected() {
        if filtered.indices.contains(selection) { onPick(filtered[selection]) }
    }

    var body: some View {
        VStack(spacing: 0) {
            TextField(L.t("Search clipboard history…"), text: $query)
                .textFieldStyle(.plain)
                .font(.system(size: 15))
                .padding(12)
                .focused($focused)
                .onKeyPress(.downArrow) { move(1); return .handled }
                .onKeyPress(.upArrow) { move(-1); return .handled }
                .onKeyPress(.escape) { onClose(); return .handled }
                .onKeyPress(characters: CharacterSet(charactersIn: "pP"), phases: .down) { press in
                    guard press.modifiers.contains(.command), filtered.indices.contains(selection) else { return .ignored }
                    togglePin(filtered[selection]); return .handled
                }
                .onSubmit { pickSelected() }
                .onChange(of: query) { _, _ in selection = 0 }
            Divider()
            if filtered.isEmpty {
                Spacer()
                Text(store.items.isEmpty ? L.t("Nothing copied yet") : L.t("No matches")).foregroundStyle(.secondary)
                Spacer()
            } else {
                ScrollViewReader { proxy in
                    ScrollView {
                        LazyVStack(spacing: 0) {
                            ForEach(Array(filtered.enumerated()), id: \.element.id) { i, item in
                                row(item, selected: i == selection).id(item.id)
                                    .contentShape(Rectangle())
                                    .onTapGesture { onPick(item) }
                            }
                        }
                    }
                    .onChange(of: selection) { _, new in
                        if filtered.indices.contains(new) { proxy.scrollTo(filtered[new].id) }
                    }
                }
            }
            Divider()
            HStack {
                Text(L.t("↩ paste   ↑↓ select   ⌘P pin   ⎋ close")).font(.system(size: 11)).foregroundStyle(.secondary)
                Spacer()
                Button(L.t("Clear unpinned")) { store.clear() }.buttonStyle(.plain).font(.system(size: 11)).foregroundStyle(.secondary)
            }
            .padding(.horizontal, 12).padding(.vertical, 8)
        }
        .frame(width: 460, height: 440)
        .background(.regularMaterial, in: RoundedRectangle(cornerRadius: 14))
        .onAppear { focused = true }
    }

    @ViewBuilder private func content(_ item: ClipItem) -> some View {
        if item.isSnippet {
            VStack(alignment: .leading, spacing: 2) {
                Text(item.title ?? "").font(.system(size: 12, weight: .semibold)).lineLimit(1)
                Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                    .font(.system(size: 11)).foregroundStyle(.secondary).lineLimit(1)
            }
        } else {
            switch item.kind {
            case .text:
                Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                    .font(.system(size: 12)).lineLimit(2).truncationMode(.tail)
            case .files:
                let names = item.paths.map { ($0 as NSString).lastPathComponent }
                Text(names.joined(separator: ", ")).font(.system(size: 12)).lineLimit(2).truncationMode(.middle)
                Text(names.count == 1 ? L.t("File") : L.f("%d files", names.count)).font(.system(size: 10)).foregroundStyle(.secondary)
            case .image:
                if let img = store.thumbnail(for: item) {
                    Image(nsImage: img).resizable().scaledToFit().frame(maxWidth: 180, maxHeight: 54, alignment: .leading)
                }
                Text(L.f("Image %@", item.imageSize ?? "")).font(.system(size: 10)).foregroundStyle(.secondary)
            }
        }
    }

    private func row(_ item: ClipItem, selected: Bool) -> some View {
        HStack(alignment: .top, spacing: 8) {
            Image(systemName: item.isSnippet ? "text.badge.star" : (item.kind == .files ? "doc.on.doc" : (item.kind == .image ? "photo" : "text.alignleft")))
                .font(.system(size: 11)).foregroundStyle(.secondary).frame(width: 16).padding(.top, 2)
            VStack(alignment: .leading, spacing: 2) {
                content(item)
                Text(Self.rel.localizedString(for: item.date, relativeTo: Date()))
                    .font(.system(size: 10)).foregroundStyle(.secondary)
            }
            Spacer(minLength: 0)
            if !item.isSnippet {
                Button { togglePin(item) } label: { Image(systemName: item.pinned ? "pin.fill" : "pin") }
                    .buttonStyle(.plain).foregroundStyle(item.pinned ? Color.accentColor : Color.secondary)
                    .help(item.pinned ? L.t("Unpin") : L.t("Pin (never deleted)"))
                if !item.pinned {
                    Button { store.remove(item) } label: { Image(systemName: "xmark.circle.fill") }
                        .buttonStyle(.plain).foregroundStyle(.tertiary)
                }
            }
        }
        .padding(.horizontal, 12).padding(.vertical, 6)
        .background(selected ? Color.accentColor.opacity(0.25) : Color.clear)
    }
}
